export type JaCourse = {
  code: string;
  slug: string;
  language: LanguageSlug;
  languageLabel: string;
  title: string;
  level: string;
  track: string;
  summary: string;
  audience: string;
  duration: string;
  frequency: string;
  classSize: string;
  outcomes: string[];
  syllabus: { unit: string; title: string; content: string }[];
};

export const jaCourses: JaCourse[] = languageCourses.map((course) => {
  const copy = copyByCode.get(course.code);
  if (!copy) throw new Error(`Missing Japanese course copy for ${course.code}`);
  return {
    code: course.code,
    slug: course.slug,
    language: course.language,
    languageLabel: { english: "英語", french: "フランス語", japanese: "日本語", korean: "韓国語" }[course.language],
    title: copy.title,
    level: copy.level,
    track: copy.track,
    summary: copy.summary,
    audience: copy.audience,
    duration: formatDuration(course.duration),
    frequency: formatFrequency(course.frequency),
    classSize: formatClassSize(course.classSize),
    outcomes: outcomesFor(copy.track),
    syllabus: copy.modules.map(([title, content], index) => ({
      unit: String(index + 1).padStart(2, "0"),
      title,
      content,
    })),
  };
});

export const jaCoursesByLanguage = (language: LanguageSlug) =>
  jaCourses.filter((c) => c.language === language);

export const findJaCourse = (language: string, slug: string) =>
  jaCourses.find((c) => c.language === language && c.slug === slug);
